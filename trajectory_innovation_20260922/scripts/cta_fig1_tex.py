"""Paper Fig. 1: turn one decision rendered by scripts/cta_fig1_data.py into TikZ data (crops, proposal paths, code
colours, score bars) and copy the frames it uses. Text processing only; no simulation or model.

Coordinates: native render pixels = PushT world units, y down. Crops are squares given as graphicx trims in bp
(the PNGs carry no DPI, so 1 px = 1 bp). Candidate numbers in the figure are 1-based (A^(1) = candidate 0).
Codes: each token's three FSQ coordinates in [-1, 1] are shown as one RGB cell, (c + 1) / 2 per channel.
"""
import argparse
import json
import math
import shutil
from pathlib import Path

VERTICES = [(-60., 30.), (60., 30.), (60., 0.), (-60., 0.), (-15., 30.), (-15., 120.), (15., 120.), (15., 30.)]
SIZE = 512.


def vertices(pose):
    x, y, a = pose
    c, s = math.cos(a), math.sin(a)
    return [(c * vx - s * vy + x, s * vx + c * vy + y) for vx, vy in VERTICES]


def square(points, pad, minimum):
    xs, ys = [p[0] for p in points], [p[1] for p in points]
    cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
    side = max(max(xs) - min(xs), max(ys) - min(ys), minimum) + 2 * pad
    x0 = min(max(cx - side / 2, 0.), SIZE - side)
    y0 = min(max(cy - side / 2, 0.), SIZE - side)
    return x0, y0, side


def trim(box):
    x0, y0, side = box
    return f"{x0:.1f} {SIZE - y0 - side:.1f} {SIZE - x0 - side:.1f} {y0:.1f}"     # left bottom right top


def local(box, p):
    x0, y0, side = box
    return (p[0] - x0) / side, 1. - (p[1] - y0) / side


def path(box, start, points):
    return " -- ".join(f"({u:.4f},{v:.4f})" for u, v in (local(box, p) for p in [start] + points))


def rgb(code):
    return ",".join(f"{min(max((c + 1.) / 2., 0.), 1.):.3f}" for c in code)


def main(a):
    rec = json.loads((a.decision / "decision.json").read_text())
    labels, scores = rec["labels"], rec["scores"]["CTA"]
    k = len(labels)
    chosen = max(range(k), key=lambda i: scores[i])
    best = max(range(k), key=lambda i: labels[i])
    worst = min(range(k), key=lambda i: labels[i])
    start, chunks = rec["agent_start"], rec["chunks"]
    goal = vertices(rec["goal_pose"])
    chunk_pts = [p for c in chunks for p in c]
    top = square([start] + chunk_pts + vertices(rec["block_start"]) + vertices(rec["block"][chosen][-1]) + goal,
                 pad=12., minimum=160.)
    prop = square([start] + chunk_pts, pad=12., minimum=96.)
    sib = [best, worst]
    bottom = square([p for i in sib for pose in rec["block"][i][1::2] for p in vertices(pose)]
                    + [p for i in sib for p in rec["agent"][i][1::2]] + goal, pad=10., minimum=120.)

    img = a.img_dir
    img.mkdir(parents=True, exist_ok=True)
    shutil.copy(a.decision / "cur.png", img / "cur.png")
    shutil.copy(a.decision / "prev.png", img / "prev.png")
    for i in set(sib) | {chosen}:
        for j in (2, 4, 6, 8):
            shutil.copy(a.decision / f"cand{i}_s{j}.png", img / f"c{i}s{j}.png")
    for g in a.goals:
        shutil.copy(a.decision.parent / f"goal{g}.png", img / f"goal{g}.png")

    lo, hi = min(scores), max(scores)
    out = [f"% Generated by scripts/cta_fig1_tex.py from {a.decision} (root {rec['root']}, decision {rec['decision']},"
           f" t = {rec['t']}). Do not edit by hand.",
           f"% CTA choice {chosen + 1}, best label {best + 1}, worst label {worst + 1} (1-based);"
           f" labels (mean vertex error, px) " + ", ".join(f"{-512 * x:.1f}" for x in labels),
           f"\\def\\FigChosen{{{chosen + 1}}}\\def\\FigBest{{{best + 1}}}\\def\\FigWorst{{{worst + 1}}}",
           f"\\def\\FigChosenIdx{{{chosen}}}\\def\\FigBestIdx{{{best}}}\\def\\FigWorstIdx{{{worst}}}",
           f"\\def\\FigGoals{{{','.join(str(g) for g in a.goals)}}}",
           f"\\def\\FigErrBest{{{-512 * labels[best]:.0f}}}\\def\\FigErrWorst{{{-512 * labels[worst]:.0f}}}"]
    for name, box in (("Top", top), ("Prop", prop), ("Bottom", bottom)):
        out.append(f"\\newcommand{{\\FigImg{name}}}[2]{{\\includegraphics[width=#1,trim={trim(box)},clip]"
                   f"{{fig/pusht/#2}}}}")
    for name, box in (("Top", top), ("Prop", prop)):
        x0, y0, side = box
        out.append(f"\\def\\FigZoom{name}{{({x0 / SIZE:.4f},{1 - (y0 + side) / SIZE:.4f}) rectangle "
                   f"({(x0 + side) / SIZE:.4f},{1 - y0 / SIZE:.4f})}}")
    for name, box in (("Top", top), ("Prop", prop)):
        lines = [f"\\draw[proposal] {path(box, start, chunks[i])};" for i in range(k) if i != chosen]
        lines.append(f"\\draw[chosenhalo] {path(box, start, chunks[chosen])};")
        lines.append(f"\\draw[chosen] {path(box, start, chunks[chosen])};")
        out.append(f"\\newcommand{{\\FigPaths{name}}}{{%\n  " + "\n  ".join(lines) + "}")
    out.append(f"\\newcommand{{\\FigChosenTop}}{{\\draw[chosenhalo] {path(top, start, chunks[chosen])};"
               f"\\draw[chosen] {path(top, start, chunks[chosen])};}}")
    colors, cells = [], []
    for i, code in enumerate(rec["expected_codes"]):
        for t, c in enumerate(code):
            colors.append(f"\\definecolor{{figP{i}t{t}}}{{rgb}}{{{rgb(c)}}}")
            cells.append(f"\\fill[figP{i}t{t}] ({{{t}*\\FigCW}},{{-{i}*\\FigRH}}) rectangle ++(\\FigCellW,\\FigCellH);")
    for row, i in enumerate(sib):
        for t, c in enumerate(rec["source_codes"][i]):
            colors.append(f"\\definecolor{{figS{row}t{t}}}{{rgb}}{{{rgb(c)}}}")
    out += colors
    out.append("\\newcommand{\\FigPredCodes}{%\n  " + "\n  ".join(cells) + "}")
    for row in range(2):
        out.append(f"\\newcommand{{\\FigSourceCode{'AB'[row]}}}{{%\n  " + "\n  ".join(
            f"\\fill[figS{row}t{t}] ({{{t}*\\FigCW}},0) rectangle ++(\\FigCellW,\\FigCellH);" for t in range(16)) + "}")
    bars = []
    for i, s in enumerate(scores):
        length = 0.08 + 0.92 * (s - lo) / (hi - lo) if hi > lo else 1.
        style = "chosenbar" if i == chosen else "bar"
        bars.append(f"\\fill[{style}] (0,{{-{i}*\\FigRH}}) rectangle ({{{length:.4f}*\\FigBW}},{{-{i}*\\FigRH+\\FigCellH}});")
    out.append("\\newcommand{\\FigBars}{%\n  " + "\n  ".join(bars) + "}")
    a.out_tex.write_text("\n".join(out) + "\n")
    print(json.dumps({"chosen": chosen, "best": best, "worst": worst, "top": top, "prop": prop, "bottom": bottom}))


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--decision", type=Path, required=True)
    p.add_argument("--out-tex", type=Path, required=True)
    p.add_argument("--img-dir", type=Path, required=True)
    p.add_argument("--goals", type=int, nargs="+", default=[0, 1, 2])
    main(p.parse_args())
